#ifndef CLEANUP_H
#define CLEANUP_H

/* Удаляет оставшиеся после сбоя временные файлы загрузок (имена с префиксом
 * FILEOPS_TMP_PREFIX) во всём дереве root. Симлинки на папки не прослеживаются,
 * удаляются только обычные файлы и симлинки, но не каталоги.
 * Вызывать при старте, пока загрузки не принимаются.
 * Возвращает число удалённых записей или -1, если root не открылся. */
int cleanup_tmp(const char *root);

#endif
